class Lang:
    """Tiny translation lookup with a mutable current language."""

    def __init__(self, code: str) -> None:
        self.code = code if code in STRINGS else "en"

    def __call__(self, key: str, **kw) -> str:
        text = STRINGS[self.code].get(key, STRINGS["en"].get(key, key))
        return text.format(**kw) if kw else text


def default_lang() -> str:
    """English by default; switch under the Language submenu (persisted)."""
    env = os.environ.get("CLAUDE_STATUS_LANG", "").lower()
    return env if env in STRINGS else "en"
